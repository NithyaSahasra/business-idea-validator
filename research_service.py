import json
import logging
from datetime import datetime, timezone
from sqlalchemy.orm import Session
from app.models import ResearchJob, Source, Report
from app.services.search_service import SearchService
from app.services.llm_service import LLMService
from app.services.scoring_service import ScoringService

logger = logging.getLogger("idealens.research")

STAGES = [
    "understanding_idea",
    "finding_competitors",
    "researching_customer_needs",
    "checking_market_demand",
    "analyzing_pricing",
    "preparing_report"
]


class ResearchService:
    @classmethod
    async def process_job(cls, db: Session, job: ResearchJob) -> bool:
        """
        Orchestrates the 6 research stages sequentially.
        Persists state transitions, sources, validated report, and deterministic opportunity score.
        """
        idea = job.idea
        try:
            # Stage 1: Understanding Idea
            cls._update_stage(db, job, "understanding_idea")
            idea_dict = {
                "name": idea.name,
                "description": idea.description,
                "problem": idea.problem,
                "target_audience": idea.target_audience,
                "geography": idea.geography,
                "category": idea.category,
                "business_model": idea.business_model,
                "known_competitors": idea.known_competitors,
            }

            # Stages 2 - 5: Multi-query Search & Evidence Gathering
            cls._update_stage(db, job, "finding_competitors")
            cls._update_stage(db, job, "researching_customer_needs")
            cls._update_stage(db, job, "checking_market_demand")
            cls._update_stage(db, job, "analyzing_pricing")

            # Collect evidence using Tavily or fixture
            raw_sources = await SearchService.collect_evidence_for_idea(
                idea_name=idea.name,
                description=idea.description,
                problem=idea.problem,
                target_audience=idea.target_audience,
                geography=idea.geography,
                category=idea.category,
                business_model=idea.business_model,
                known_competitors=idea.known_competitors
            )

            # Persist sources to obtain database IDs for strict citations
            # First clean any previous sources if this was a retried attempt
            db.query(Source).filter(Source.research_job_id == job.id).delete()
            db.flush()

            persisted_sources = []
            for s in raw_sources:
                source_record = Source(
                    research_job_id=job.id,
                    title=s["title"],
                    url=s["url"],
                    source_type=s["source_type"],
                    retrieved_at=s["retrieved_at"],
                    evidence_summary=s["evidence_summary"],
                    relevance_score=s.get("relevance_score")
                )
                db.add(source_record)
                persisted_sources.append(source_record)

            db.commit()

            # Refresh to get autogenerated IDs
            for s in persisted_sources:
                db.refresh(s)

            sources_for_llm = [
                {
                    "id": s.id,
                    "title": s.title,
                    "url": s.url,
                    "source_type": s.source_type,
                    "evidence_summary": s.evidence_summary
                }
                for s in persisted_sources
            ]

            # Stage 6: Preparing Report
            cls._update_stage(db, job, "preparing_report")

            structured_report = await LLMService.synthesize_validation_report(
                idea=idea_dict,
                sources=sources_for_llm
            )

            # Calculate deterministic opportunity score
            final_score, score_status, validated_dims = ScoringService.calculate_opportunity_score(
                assessments=structured_report.dimension_assessments,
                credible_sources_count=len(persisted_sources)
            )

            # Update structured report with validated dimensions
            structured_report.dimension_assessments = validated_dims

            # Persist Report record
            # Remove any previous report for this job if retrying
            db.query(Report).filter(Report.research_job_id == job.id).delete()
            db.flush()

            report_record = Report(
                research_job_id=job.id,
                executive_summary=structured_report.executive_summary,
                opportunity_score=final_score,
                score_status=score_status,
                structured_report=json.dumps(structured_report.model_dump())
            )
            db.add(report_record)

            # Mark job completed
            job.status = "completed"
            job.current_stage = "completed"
            job.completed_at = datetime.now(timezone.utc)
            job.error_code = None
            job.error_message = None
            job.progress_updated_at = datetime.now(timezone.utc)
            db.commit()
            logger.info(f"Research job {job.id} completed successfully.")
            return True

        except Exception as e:
            logger.exception(f"Research job {job.id} failed: {e}")
            db.rollback()
            job.status = "failed"
            job.error_code = "RESEARCH_PIPELINE_ERROR"
            job.error_message = str(e)
            job.progress_updated_at = datetime.now(timezone.utc)
            db.commit()
            return False

    @staticmethod
    def _update_stage(db: Session, job: ResearchJob, stage: str):
        job.current_stage = stage
        job.progress_updated_at = datetime.now(timezone.utc)
        db.commit()
